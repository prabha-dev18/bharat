export function getServiceBySlug(slug) {
  if (!slug) return null;
  const cleanSlug = slug.toLowerCase().trim();
  if (servicesDetailData[cleanSlug]) {
    return servicesDetailData[cleanSlug];
  }

  for (const service of Object.values(servicesDetailData)) {
    if (service.aliases && service.aliases.includes(cleanSlug)) {
      return service;
    }
  }
  return null;
}

export function getAllServices() {
  return Object.values(servicesDetailData);
}
