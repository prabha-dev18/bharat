export function getSchemeBySlug(slug) {
  if (!slug) return null;
  const cleanSlug = slug.toLowerCase().trim();
  if (schemesDetailData[cleanSlug]) {
    return schemesDetailData[cleanSlug];
  }
  for (const scheme of Object.values(schemesDetailData)) {
    if (scheme.aliases && scheme.aliases.includes(cleanSlug)) {
      return scheme;
    }
  }
  return null;
}

export function getAllSchemes() {
  return Object.values(schemesDetailData);
}
